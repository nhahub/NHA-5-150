"""
src/support.py - Low-Confidence Support Functions for Smart Shelf.

Provides shared functions to calculate support cell density from the training period
and flag low-confidence predictions across Track 3A (spoilage classifier),
Track 3B (revenue-response regressor), and Track 3C (discount optimizer).

The low-confidence flag measures data sparsity: specifically, how many training rows
exist for a given product at a given store (product_name x store_id). Batches with
fewer than 20 historical training observations (or unseen product-store pairs) are
flagged as low confidence.
"""

from typing import Sequence, Tuple, Union
import numpy as np
import pandas as pd

# Standard support definitions for Smart Shelf (Decision 5)
DEFAULT_SUPPORT_KEYS: Tuple[str, ...] = ("product_name", "store_id")
DEFAULT_SUPPORT_THRESHOLD: int = 20


def compute_support(
    df_train: pd.DataFrame,
    keys: Sequence[str] = DEFAULT_SUPPORT_KEYS,
) -> pd.DataFrame:
    """
    Computes cell sample counts from the training partition only.

    Measures how many historical training rows exist for each combination of
    keys (default: product_name x store_id).

    Parameters
    ----------
    df_train : pd.DataFrame
        Training partition data (must not contain test rows).
    keys : Sequence[str], default ("product_name", "store_id")
        Grouping column names defining support cells.

    Returns
    -------
    pd.DataFrame
        A DataFrame with the grouping keys and a 'cell_count' column.
    """
    keys_list = list(keys)
    for k in keys_list:
        if k not in df_train.columns:
            raise KeyError(f"Support key '{k}' not found in training DataFrame.")

    support = (
        df_train.groupby(keys_list, observed=True)
        .size()
        .reset_index(name="cell_count")
    )
    return support


def flag_low_confidence(
    df: pd.DataFrame,
    support_table: pd.DataFrame,
    threshold: int = DEFAULT_SUPPORT_THRESHOLD,
    keys: Sequence[str] = DEFAULT_SUPPORT_KEYS,
) -> pd.Series:
    """
    Flags rows as low confidence if their training support cell count is strictly
    below the threshold (cell_count < threshold).

    Measures data sparsity: how many training rows exist for that product at that
    store. Cells never seen in training receive a count of 0 and are automatically
    flagged.

    Parameters
    ----------
    df : pd.DataFrame
        Target DataFrame (e.g. test set or incoming prediction batches).
    support_table : pd.DataFrame
        Support table generated by `compute_support` on the training partition.
    threshold : int, default 20
        Minimum required training cell count to be considered high confidence.
    keys : Sequence[str], default ("product_name", "store_id")
        Grouping column names used to join with the support table.

    Returns
    -------
    pd.Series
        Boolean Series of length len(df), with True indicating low confidence.
    """
    keys_list = list(keys)
    for k in keys_list:
        if k not in df.columns:
            raise KeyError(f"Support key '{k}' not found in target DataFrame.")
        if k not in support_table.columns:
            raise KeyError(f"Support key '{k}' not found in support table.")

    if "cell_count" not in support_table.columns:
        raise KeyError("'cell_count' column missing from support table.")

    # Left merge to preserve exact target DataFrame row order and index
    merged = df[keys_list].merge(
        support_table[keys_list + ["cell_count"]],
        on=keys_list,
        how="left",
    )
    # Unseen cells in training count as 0 and are flagged
    counts = merged["cell_count"].fillna(0).values

    flagged = pd.Series(counts < threshold, index=df.index, name="is_low_confidence")
    return flagged


def _run_unit_tests() -> None:
    """Internal unit tests for support calculation and threshold flagging."""
    # 1. Synthetic training partition
    df_train_synth = pd.DataFrame({
        "product_name": ["Organic Milk", "Organic Milk", "Organic Milk", "Artisan Bread", "Greek Yogurt"],
        "store_id": ["STORE_001", "STORE_001", "STORE_001", "STORE_002", "STORE_003"],
    })

    supp = compute_support(df_train_synth)
    assert len(supp) == 3, f"Expected 3 distinct cells, got {len(supp)}"
    row_milk = supp[(supp["product_name"] == "Organic Milk") & (supp["store_id"] == "STORE_001")]
    assert row_milk["cell_count"].iloc[0] == 3, "Incorrect count for (Organic Milk, STORE_001)"

    # 2. Target partition containing seen and completely unseen product x store cells
    df_target_synth = pd.DataFrame({
        "product_name": ["Organic Milk", "Artisan Bread", "Wild Salmon"],  # Wild Salmon is unseen
        "store_id": ["STORE_001", "STORE_002", "STORE_099"],  # STORE_099 is unseen
    })

    # Test with threshold = 2:
    # (Organic Milk, STORE_001) count=3 >= 2 -> not flagged (False)
    # (Artisan Bread, STORE_002) count=1 < 2 -> flagged (True)
    # (Wild Salmon, STORE_099) count=0 (unseen) < 2 -> flagged (True)
    flagged_th2 = flag_low_confidence(df_target_synth, supp, threshold=2)
    assert len(flagged_th2) == 3, "Flag length mismatch"
    assert not flagged_th2.iloc[0], "Seen cell with count 3 should not be flagged at threshold 2"
    assert flagged_th2.iloc[1], "Seen cell with count 1 should be flagged at threshold 2"
    assert flagged_th2.iloc[2], "Unseen cell with count 0 must be flagged at threshold 2"

    # Test default threshold (20) and default keys:
    flagged_default = flag_low_confidence(df_target_synth, supp)
    assert flagged_default.all(), "All rows with count < 20 must be flagged at default threshold 20"

    # Test custom keys override
    df_train_custom = pd.DataFrame({
        "category": ["Dairy", "Dairy"],
        "region": ["West", "West"],
    })
    supp_custom = compute_support(df_train_custom, keys=("category", "region"))
    assert len(supp_custom) == 1
    assert supp_custom["cell_count"].iloc[0] == 2

    print("[src/support.py] All unit tests passed cleanly.")


if __name__ == "__main__":
    _run_unit_tests()

