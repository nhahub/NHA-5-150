"""
src/support.py - Low-Confidence Support Functions for Smart Shelf.

Provides shared functions to calculate support cell density from the training period
and flag low-confidence predictions across Track 3A (spoilage classifier),
Track 3B (revenue-response regressor), and Track 3C (discount optimizer).
"""

from typing import Sequence, Union
import numpy as np
import pandas as pd


def compute_support(
    df_train: pd.DataFrame,
    keys: Sequence[str] = ("category", "region", "store_id"),
) -> pd.DataFrame:
    """
    Computes cell sample counts from the training partition only.

    Parameters
    ----------
    df_train : pd.DataFrame
        Training partition data (must not contain test rows).
    keys : Sequence[str], default ("category", "region", "store_id")
        Grouping column names defining support cells.

    Returns
    -------
    pd.DataFrame
        A DataFrame with the grouping keys and a 'cell_count' column.
    """
    keys_list = list(keys)
    for k in keys_list:
        if k not in df_train.columns:
            raise KeyError(f"Support key '{k}' not found in training DataFrame.")

    support = (
        df_train.groupby(keys_list, observed=True)
        .size()
        .reset_index(name="cell_count")
    )
    return support


def flag_low_confidence(
    df: pd.DataFrame,
    support_table: pd.DataFrame,
    threshold: int = 30,
    keys: Sequence[str] = ("category", "region", "store_id"),
) -> pd.Series:
    """
    Flags rows as low confidence if their support cell count falls below threshold.

    Cells unseen in the training support table receive a count of 0 and are
    automatically flagged.

    Parameters
    ----------
    df : pd.DataFrame
        Target DataFrame (e.g. test set or new incoming batches).
    support_table : pd.DataFrame
        Support table generated by `compute_support` on the training partition.
    threshold : int, default 30
        Minimum required training cell count to be considered high confidence.
    keys : Sequence[str], default ("category", "region", "store_id")
        Grouping column names used to join with the support table.

    Returns
    -------
    pd.Series
        Boolean Series of length len(df), with True indicating low confidence.
    """
    keys_list = list(keys)
    for k in keys_list:
        if k not in df.columns:
            raise KeyError(f"Support key '{k}' not found in target DataFrame.")
        if k not in support_table.columns:
            raise KeyError(f"Support key '{k}' not found in support table.")

    if "cell_count" not in support_table.columns:
        raise KeyError("'cell_count' column missing from support table.")

    # Left merge to preserve exact target DataFrame row order and index
    merged = df[keys_list].merge(
        support_table[keys_list + ["cell_count"]],
        on=keys_list,
        how="left",
    )
    # Unseen cells in training are imputed with 0
    counts = merged["cell_count"].fillna(0).values

    flagged = pd.Series(counts < threshold, index=df.index, name="is_low_confidence")
    return flagged
